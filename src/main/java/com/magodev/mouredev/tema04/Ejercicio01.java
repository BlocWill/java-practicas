// 1- Crear una variable con el resultado de cada operacion aritmetica

package com.magodev.mouredev.tema04;

public class Ejercicio01 {
    public static void main(String[] args) {

        var number = 7;
        var number2 = 5;

        System.out.println(number + number2);
        System.out.println(number - number2);
        System.out.println(number * number2);
        System.out.println(number / number2);
        System.out.println(number % number2);
    }


}
