// 3- Imprimir tres comparaciones verdaderas con diferentes operadores de comparacion

package com.magodev.mouredev.tema04;

public class Ejercicio03 {
    public static void main(String[] args) {

        var valor = 5;
        var valor2 = 8;

        System.out.println(valor != valor2);
        System.out.println(valor < valor2);
        System.out.println(valor2 > valor);
    }
}
